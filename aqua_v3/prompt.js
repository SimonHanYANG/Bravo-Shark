/* ---------- 四、组装：把五层拼成真正发给模型的消息 ---------- */
function tuneSystem(stage,ctx){
  var tk=TUNE.tasks[stage];
  if(!tk) return TUNE.identity;
  var parts=[
    TUNE.identity,
    TUNE.factorBlock(ctx),
    "\n【本轮任务：" + tk.t + "】\n" + tk.ask
  ];
  var sh=TUNE.shots[stage];
  if(sh) parts.push("\n" + sh.join("\n"));
  parts.push(TUNE.selfcheck);
  return parts.join("\n");
}
function tuneMessages(stage,ctx,userInput){
  return [{role:"system",content:tuneSystem(stage,ctx)},
          {role:"user",content:String(userInput||"")}];
}
