/* ---------------- 时限：只做加法，不做判断 ---------------- */
function disDeadline(){
  var d=disState();
  if(!d.date) return null;
  var t=new Date(d.date+"T00:00:00");
  if(isNaN(t.getTime())) return null;
  var end=new Date(t.getTime()); end.setFullYear(end.getFullYear()+1);
  var now=new Date();
  var days=Math.ceil((end-now)/86400000);
  return {start:t, end:end, days:days};
}
function disFmtDate(d){
  return d.getFullYear()+"-"+("0"+(d.getMonth()+1)).slice(-2)+"-"+("0"+d.getDate()).slice(-2);
}

