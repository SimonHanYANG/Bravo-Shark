var HC_LV = ["无", "轻度", "明显", "拉满"];

/* 一段话 → 高语境度 / 阴阳怪气度 / 命中信号 / 真实意思 / 怎么破 */
function hcAnalyze(text){
  var t = String(text || "");
  var hits = [], ctx = 0, ya = 0;
  for (var i = 0; i < HC_SIGNALS.length; i++){
    var g = HC_SIGNALS[i];
    var m = t.match(g.re);
    if (!m) continue;
    hits.push({ n:g.n, why:g.why, say:g.say, fix:g.fix, hit:m[0], ctx:g.ctx, ya:g.ya });
    ctx += g.ctx; ya += g.ya;
  }
  function lv(s){
    if (!s) return 0;
    if (s <= 2) return 1;
    if (s <= 4) return 2;
    return 3;
  }
  var cl = lv(ctx), yl = lv(ya);
  /* 真实意思：取阴阳权重最高的两条信号的话，没有就直接说 */
  var top = hits.slice().sort(function(a, b){ return b.ya - a.ya; });
  var say = top.length
    ? top.slice(0, 2).map(function(x){ return x.say; }).join(" / ")
    : "这句话没有明显的高语境包装，按字面理解即可。";
  var fix = top.length
    ? top[0].fix
    : "字面直白的话，最好的回应就是把事实和条件说清楚。";
  return {
    ctx: ctx, ya: ya, ctxLv: cl, yaLv: yl,
    ctxName: HC_LV[cl], yaName: HC_LV[yl],
    hits: hits,
    real: say, breakIt: fix,
    hard: (yl >= 3)
  };
}

/* 分析结果的 HTML —— App 内视图与独立小工具共用，避免两边显示不一致 */
function hcBoxHTML(hc){
  if (!hc) return "";
  var h = '<div class="hcbox">' +
    '<div class="hchd"><b>高语境 / 阴阳怪气分析</b>' +
    (hc.yaLv >= 2 ? '<span class="hcbad">阴阳 ' + hc.yaName + '</span>' : '') + '</div>' +
    '<div class="hcmeters">' +
      '<div class="hcm"><i>高语境度（靠共享语境传意）</i>' +
        '<span class="hcl lv' + hc.ctxLv + '">' + hc.ctxName + '</span>' +
        '<u><b style="width:' + Math.min(100, hc.ctx * 14) + '%"></b></u></div>' +
      '<div class="hcm"><i>阴阳怪气度（正话包装负评）</i>' +
        '<span class="hcl lv' + hc.yaLv + '">' + hc.yaName + '</span>' +
        '<u><b style="width:' + Math.min(100, hc.ya * 16) + '%"></b></u></div>' +
    '</div>';
  if (hc.hits.length){
    h += '<ul class="hcsig">' + hc.hits.map(function(x){
      return '<li><b>' + esc(x.n) + '</b><em>「' + esc(x.hit) + '」</em><span>' + esc(x.why) + '</span></li>';
    }).join("") + '</ul>';
  } else {
    h += '<div class="hcrow"><i>信号</i><span>没命中任何高语境或阴阳包装的信号：' +
      '按字面理解就行，不用过度解读。</span></div>';
  }
  h += '<div class="hcrow real"><i>高语境下的真实意思</i><span>' + esc(hc.real) + '</span></div>';
  h += '<div class="hcrow fix"><i>怎么破</i><span>' + esc(hc.breakIt) + '</span></div>';
  h += '</div>';
  return h;
}
