/* ---------------- 匹配：关键词命中 + 2-gram 重合 ---------------- */
function bbxNorm(s){
  return String(s == null ? "" : s)
    .replace(/[\s，,。、；;：:（）()【】\[\]！!？?～~…"'"'《》·]/g, "")
    .toLowerCase();
}
function bbxGrams(s){
  var t = bbxNorm(s), o = [];
  for (var i = 0; i < t.length - 1; i++) o.push(t.slice(i, i + 2));
  return o;
}
/* 高权威匹配：原句命中 / 关键词命中 / 2-gram 重合度 */
function bbxScore(item, t, tg){
  var sc = 0, hitK = [];
  var si = bbxNorm(item.s);
  if (t.indexOf(si) >= 0) sc += 12;                 /* 原话本身就出现了 */
  (item.k || []).forEach(function(k){
    if (t.indexOf(bbxNorm(k)) >= 0) { sc += 4; hitK.push(k); }
  });
  var ig = bbxGrams(item.s), m = 0;
  for (var i = 0; i < ig.length; i++) if (tg.indexOf(ig[i]) >= 0) m++;
  if (ig.length) sc += (m / ig.length) * 7;
  return {sc: sc, hitK: hitK};
}
function bbxMatch(text, n){
  var t = bbxNorm(text), tg = bbxGrams(text);
  if (t.length < 2) return [];
  var out = [];
  for (var i = 0; i < BBX.length; i++){
    var r = bbxScore(BBX[i], t, tg);
    if (r.sc >= 3.2) out.push({it: BBX[i], sc: r.sc, hitK: r.hitK});
  }
  out.sort(function(a, b){ return b.sc - a.sc; });
  return out.slice(0, n || 3);
}
/* 没有命中时：识别「这是哪一类话」+ 通用读法 */
