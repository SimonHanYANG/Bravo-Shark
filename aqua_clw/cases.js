function caseHost(kind){
  if(kind==="dis"){
    return '<div class="casehero">'+
      '<div class="casehero-l"><b>看看别人遇到过的同类事</b>'+
      '<span>'+DIS_CASES.length+' 个匿名整理的常见场景。不是让你照着做，'+
      '只是想让你知道：这种事很多人遇到过，你不是特例。</span></div>'+
      '<button class="casehero-b" type="button" id="caseOpen">进去看看</button></div>';
  }
  return '<div class="casehero">'+
    '<div class="casehero-l"><b>别人在学什么</b>'+
    '<span>'+GROW_CASES.length+' 份匿名整理的学习记录：学什么、花了多久、卡在哪一步。'+
    '看看别人是怎么开始的，也许比「从哪学起」这个问题更有用。</span></div>'+
    '<button class="casehero-b" type="button" id="caseOpen">看看别人</button></div>';
}

/* 挂到某个容器。已经挂过就不重复挂（切视图会反复调用）。 */
function mountCaseCta(hostId, kind){
  var host=document.getElementById(hostId);
  if(!host || host.getAttribute("data-mounted")) return;
  host.innerHTML=caseHost(kind);
  host.setAttribute("data-mounted","1");
  var b=document.getElementById("caseOpen");
  if(b) b.onclick=function(){ openCaseBook(kind); };
}

/* 列表弹窗 */
function openCaseBook(kind){
  var isDis=(kind==="dis"), arr=isDis?DIS_CASES:GROW_CASES;
  var h='<p class="note" style="margin-top:0">'+(isDis?CASE_SRC_DIS:CASE_SRC_GROW)+'</p>';
  h+='<div class="caselist">';
  arr.forEach(function(c,i){
    h+='<button class="caseitem" type="button" data-ci="'+i+'">'+
      '<i>'+esc(c.d)+'</i>'+
      '<b>'+esc(c.t||c.k)+'</b>'+
      '<span>'+esc(c.s)+'</span>'+
      '<em>看详情 →</em></button>';
  });
  h+='</div>';
  if(isDis){
    h+='<p class="tbnote">★ 每个人的合同、证据、当地裁审口径都不同，这些经历<b>不能照搬</b>。'+
       '要不要采取行动、怎么行动，请与执业律师或有管辖权的机构确认。</p>';
  }
  openModal(isDis?"别人的情况 · 匿名整理":"别人在学什么 · 匿名整理", h, []);
  var host=document.getElementById("mBody")||document;
  Array.prototype.forEach.call(host.querySelectorAll("[data-ci]"),function(b){
    b.onclick=function(){ openCaseOne(kind, +b.dataset.ci); };
  });
}

/* 单条详情 */
function openCaseOne(kind, i){
  var isDis=(kind==="dis"), arr=isDis?DIS_CASES:GROW_CASES;
  var c=arr[i]; if(!c) return;
  var h='<p class="note" style="margin-top:0">'+esc(c.d)+'</p>';
  h+='<h4 class="caseq">'+esc(c.t||c.k)+'</h4>';
  h+='<div class="caseblk"><b>当时的情况</b><p>'+esc(c.s)+'</p></div>';
  h+='<div class="caseblk"><b>'+(isDis?"他做了什么":"他怎么做")+'</b><ul class="rvwhy">';
  c.did.forEach(function(x){ h+='<li>'+esc(x)+'</li>'; });
  h+='</ul></div>';
  h+='<div class="caseblk"><b>后来</b><p>'+esc(c.how)+'</p></div>';
  h+='<div class="caseles"><b>一句能带走的</b><p>'+esc(c.les)+'</p></div>';
  h+='<p class="tbnote">★ 这是匿名整理的一段经历，不是建议，也不代表你的情况会一样。'+
     (isDis?'本模块不提供法律意见、不预测结果、不计算金额。':'每个人的起点和时间都不一样，不必拿它跟自己比。')+'</p>';
  openModal(isDis?"别人的经历":"别人的学习记录", h, [
    {t:"返回列表", f:function(){ openCaseBook(kind); }},
    {t:"关掉", c:"pri", f:closeModal}
  ]);
}

