/* =====================================================================
   别人的情况 ： 劳议鲨手 / 进化雷达 两个「同类案例库」
   ---------------------------------------------------------------------
   ★ 这个模块最容易犯的错是「编」。所以先把边界写死：

     1. 每一条都明确标注来源：整理自公开的劳动仲裁报道、职业社群讨论、
        公开的学习社区分享，做了匿名化处理。**不声称是本产品的用户数据**
        ： 产品还没有用户，说成「用户真实反馈」就是编。
     2. 不写「照做就能赢」。劳议鲨手的每一条都明写「每个人的合同、
        证据、地区裁审口径都不同，不能照搬」，并复用产品既有的
        三条硬边界（不提供法律意见 / 不预测结果 / 不计算金额）。
     3. 学习那条不写「学完就能涨薪」。只写「他花了多久、卡在哪、
        后来能做什么」： 可核验的部分，不写承诺。

   结构：每组一个列表（谁 / 什么事 / 一句话），点进去看详情（做了什么 / 后来）。
   ===================================================================== */

